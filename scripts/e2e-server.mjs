/**
 * The shop for the browser tests (npm run test:e2e, and CI): the built site (npm run build) served
 * by `wrangler dev` on http://127.0.0.1:8799, with
 *  - its own database folder (apps/worker/.wrangler/e2e), migrated and seeded from scratch on
 *    every start: the developer's local database is never touched;
 *  - a copy of wrangler.jsonc without the Workers AI binding, which needs a Cloudflare login
 *    (the assistant then answers with its rules alone);
 *  - fixed test secrets (e2e/e2e.vars), no .dev.vars.
 */
import { spawn, spawnSync } from "node:child_process";
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const worker = join(root, "apps", "worker");
const persist = join(worker, ".wrangler", "e2e");
const config = join(worker, "wrangler.e2e.jsonc");
export const PORT = 8799;

if (!existsSync(join(root, "dist", "index.html"))) {
  console.error("✗ No build: run `npm run build` first.");
  process.exit(1);
}

// the config without the bindings that need Cloudflare
const source = readFileSync(join(worker, "wrangler.jsonc"), "utf8");
const stripped = source.replace(/^\s*"ai":\s*\{[^}]*\},?\s*$/gm, "");
if (/"ai":/.test(stripped)) throw new Error("e2e-server: could not remove the ai binding from wrangler.jsonc");
writeFileSync(config, `// generated by scripts/e2e-server.mjs (git-ignored)\n${stripped}`);

// paths relative to apps/worker: Windows' shell splits absolute ones at the space of "Henine beauty"
const CONFIG = "wrangler.e2e.jsonc";
const PERSIST = ".wrangler/e2e";
const wrangler = (args, opts = {}) =>
  spawnSync("npx", ["wrangler", ...args, "--config", CONFIG], { cwd: worker, stdio: "inherit", shell: process.platform === "win32", ...opts });
const local = ["--local", "--persist-to", PERSIST];

rmSync(persist, { recursive: true, force: true });
const steps = [
  ["d1", "migrations", "apply", "DB", ...local],
  ...["geo", "base", "demo"].map((f) => ["d1", "execute", "DB", ...local, "--file", `../../packages/db/seed/${f}.sql`]),
  ["d1", "execute", "DB", ...local, "--file", "../../e2e/fixtures.sql"],
];
for (const args of steps) {
  const r = wrangler(args, { env: { ...process.env, CI: "1" } });
  if (r.status !== 0) process.exit(r.status ?? 1);
}

/*
 * The dev server, watched: its engine (workerd) can die while wrangler itself keeps running, so
 * the server just stops answering and every following test fails with "connection refused"
 * although nothing is wrong with the shop. Health is checked every 5 s once it is up; after 3
 * misses in a row (or if wrangler exits) the whole process tree is replaced, on the same
 * database. Stopped for good when the tests end.
 */
const MAX_RESTARTS = 3;
const HEALTH = `http://127.0.0.1:${PORT}/api/health`;
let dev;
let restarts = 0;
let stopping = false;
let up = false;
let misses = 0;

// The server and everything it started. It stays in this script's process group, so the test
// runner's own cleanup still reaches it at the end (a separate group once left CI hanging).
const killTree = (child) => {
  if (!child?.pid) return;
  if (process.platform === "win32") {
    spawnSync("taskkill", ["/pid", String(child.pid), "/T", "/F"], { stdio: "ignore" });
    return;
  }
  const table = spawnSync("ps", ["-A", "-o", "pid=,ppid="], { encoding: "utf8" }).stdout ?? "";
  const kids = new Map();
  for (const line of table.trim().split("\n")) {
    const [pid, ppid] = line.trim().split(/\s+/).map(Number);
    if (!kids.has(ppid)) kids.set(ppid, []);
    kids.get(ppid).push(pid);
  }
  const all = [];
  const walk = (pid) => {
    all.push(pid);
    for (const k of kids.get(pid) ?? []) walk(k);
  };
  walk(child.pid);
  for (const pid of all.reverse()) {
    try {
      process.kill(pid, "SIGKILL");
    } catch {
      /* already gone */
    }
  }
};

const restart = (why) => {
  if (stopping) return;
  if (restarts >= MAX_RESTARTS) {
    console.error(`✗ e2e server: ${why}, ${restarts} restarts already: giving up.`);
    stopping = true;
    killTree(dev);
    process.exit(1);
  }
  restarts++;
  console.error(`⚠ e2e server: ${why}: restarting (${restarts}/${MAX_RESTARTS}).`);
  const old = dev;
  dev = null;
  old?.removeAllListeners("exit");
  killTree(old);
  up = false;
  misses = 0;
  setTimeout(start, 1500);
};

const start = () => {
  dev = spawn(
    "npx",
    ["wrangler", "dev", "--config", CONFIG, "--persist-to", PERSIST, "--env-file", "../../e2e/e2e.vars", "--ip", "127.0.0.1", "--port", String(PORT), "--show-interactive-dev-session=false"],
    { cwd: worker, stdio: "inherit", shell: process.platform === "win32" },
  );
  dev.on("exit", (code) => (stopping ? process.exit(0) : restart(`wrangler exited (code ${code})`)));
};

setInterval(async () => {
  if (stopping || !dev) return;
  const ok = await fetch(HEALTH, { signal: AbortSignal.timeout(4000) }).then((r) => r.ok, () => false);
  if (ok) {
    up = true;
    misses = 0;
  } else if (up && ++misses >= 3) restart("not answering");
}, 5000).unref();

start();
const stop = () => {
  stopping = true;
  killTree(dev);
  process.exit(0);
};
process.on("SIGINT", stop);
process.on("SIGTERM", stop);
